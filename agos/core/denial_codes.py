"""
AGOS 3.2 Standardized Denial Reason Codes.

All PolicyEngine denials should reference one of these codes
to enable structured monitoring, alerting, and forensic analysis.
"""

# Authorization failures
APPROVAL_REQUIRED = "APPROVAL_REQUIRED"
APPROVAL_NOT_CONSUMED = "APPROVAL_NOT_CONSUMED"
APPROVAL_EXPIRED = "APPROVAL_EXPIRED"
APPROVAL_OPERATION_MISMATCH = "APPROVAL_OPERATION_MISMATCH"
APPROVAL_TARGET_MISMATCH = "APPROVAL_TARGET_MISMATCH"
APPROVAL_SCOPE_MISMATCH = "APPROVAL_SCOPE_MISMATCH"

# State failures
INVALID_STATE = "INVALID_STATE"
READ_ONLY_STATE = "READ_ONLY_STATE"
VERIFY_FAIL_NO_COMMIT = "VERIFY_FAIL_NO_COMMIT"
INVALID_STATE_FOR_COMMIT = "INVALID_STATE_FOR_COMMIT"

# Scope failures
OUTSIDE_SCOPE = "OUTSIDE_SCOPE"
SCOPE_HASH_MISMATCH = "SCOPE_HASH_MISMATCH"

# Target failures
SENSITIVE_TARGET = "SENSITIVE_TARGET"
APPROVAL_TARGET_BINDING_FAILED = "APPROVAL_TARGET_BINDING_FAILED"

# Integrity failures
PLAN_HASH_MISMATCH = "PLAN_HASH_MISMATCH"
EVIDENCE_HASH_MISMATCH = "EVIDENCE_HASH_MISMATCH"
STALE_VERIFICATION = "STALE_VERIFICATION"

# Payload failures
PAYLOAD_NOT_AUTHORIZED = "PAYLOAD_NOT_AUTHORIZED"
PAYLOAD_HIGH_RISK = "PAYLOAD_HIGH_RISK"
PAYLOAD_FORBIDDEN_PATTERN = "PAYLOAD_FORBIDDEN_PATTERN"
PAYLOAD_PROTECTED_SYMBOL_REMOVED = "PAYLOAD_PROTECTED_SYMBOL_REMOVED"
DIFF_TOO_LARGE = "DIFF_TOO_LARGE"

# Bypass attempts
DIRECT_TOOL_BYPASS = "DIRECT_TOOL_BYPASS"
MCP_MUTATION_DENIED = "MCP_MUTATION_DENIED"

# Capability failures  
PUSH_DENIED = "PUSH_DENIED"
DEPLOY_DENIED = "DEPLOY_DENIED"

# System & Tool-Call Validation failures
FAIL_CLOSED = "FAIL_CLOSED"
POLICY_ERROR = "POLICY_ERROR"
INVALID_TOOL_ARGUMENTS = "INVALID_TOOL_ARGUMENTS"

# Engineering, Architecture & Quality Failures (AGOS 5.0)
ARCH_MAX_FILE_SIZE_EXCEEDED = "ARCH_MAX_FILE_SIZE_EXCEEDED"
ANTI_AMPUTATION_VIOLATION = "ANTI_AMPUTATION_VIOLATION"
RUNTIME_SMOKE_FAILED = "RUNTIME_SMOKE_FAILED"

# All codes for validation
ALL_DENIAL_CODES = {
    APPROVAL_REQUIRED, APPROVAL_NOT_CONSUMED, APPROVAL_EXPIRED,
    APPROVAL_OPERATION_MISMATCH, APPROVAL_TARGET_MISMATCH, APPROVAL_SCOPE_MISMATCH,
    INVALID_STATE, READ_ONLY_STATE, VERIFY_FAIL_NO_COMMIT, INVALID_STATE_FOR_COMMIT,
    OUTSIDE_SCOPE, SCOPE_HASH_MISMATCH,
    SENSITIVE_TARGET, APPROVAL_TARGET_BINDING_FAILED,
    PLAN_HASH_MISMATCH, EVIDENCE_HASH_MISMATCH, STALE_VERIFICATION,
    PAYLOAD_NOT_AUTHORIZED, PAYLOAD_HIGH_RISK, PAYLOAD_FORBIDDEN_PATTERN,
    PAYLOAD_PROTECTED_SYMBOL_REMOVED, DIFF_TOO_LARGE,
    DIRECT_TOOL_BYPASS, MCP_MUTATION_DENIED,
    PUSH_DENIED, DEPLOY_DENIED,
    FAIL_CLOSED, POLICY_ERROR, INVALID_TOOL_ARGUMENTS,
    ARCH_MAX_FILE_SIZE_EXCEEDED, ANTI_AMPUTATION_VIOLATION, RUNTIME_SMOKE_FAILED,
}

def is_valid_denial_code(code: str) -> bool:
    return code in ALL_DENIAL_CODES
